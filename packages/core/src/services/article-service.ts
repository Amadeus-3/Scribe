function parseStoredCmsCredentials(
  cmsType: CmsCredentials['cmsType'],
  ciphertext: string | null,
): CmsCredentials {
  if (!ciphertext) {
    throw new ArticlePublishError('Add CMS credentials to the site before publishing.');
  }
  const raw = JSON.parse(decryptSecret(ciphertext)) as unknown;
  const base = raw && typeof raw === 'object' ? raw : {};
  return CmsCredentialsSchema.parse('cmsType' in base ? base : { cmsType, ...base });
}

function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

export function renderBasicMarkdownToHtml(markdown: string): string {
  const lines = markdown.split(/\r?\n/);
  const html: string[] = [];
  let inList = false;

  const closeList = () => {
    if (inList) {
      html.push('</ul>');
      inList = false;
    }
  };

  for (const rawLine of lines) {
    const line = rawLine.trim();
    if (!line) {
      closeList();
      continue;
    }

    const heading = line.match(/^(#{1,3})\s+(.+)$/);
    if (heading) {
      closeList();
      const level = heading[1]?.length ?? 2;
      html.push(`<h${level}>${escapeHtml(heading[2] ?? '')}</h${level}>`);
      continue;
    }

    const listItem = line.match(/^[-*]\s+(.+)$/);
    if (listItem) {
      if (!inList) {
        html.push('<ul>');
        inList = true;
      }
      html.push(`<li>${escapeHtml(listItem[1] ?? '')}</li>`);
      continue;
    }

    closeList();
    html.push(`<p>${escapeHtml(line)}</p>`);
  }

  closeList();
  return html.join('\n');
}

function wordCount(markdown: string): number {
  const words = markdown.trim().match(/\S+/g);
  return words?.length ?? 0;
}

function readTimeLabel(words: number | null): string {
  return `${Math.max(1, Math.ceil((words ?? 0) / 200))} min read`;
}

function normalizeSlug(slug: string): string {
  return slug
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 120);
}

function coerceBannedPhrases(value: unknown): string[] {
  return Array.isArray(value) ? value.filter((p): p is string => typeof p === 'string') : [];
}

/**
 * Score an article's on-page SEO deterministically. Advisory only — the result
 * is stored on the article for the reviewer but never changes its status or the
 * human approval gate (Spec §10.1).
 */
function buildSeoReport(args: {
  title: string | null;
  slug: string | null;
  metaDescription: string | null;
  contentMarkdown: string | null;
  imagePrompt: string | null;
  keyword: string;
  bannedPhrases: string[];
  inlineImageCount: number;
  /** Number of other published posts available to link to — drives the internal-link check. */
  internalLinkCandidates?: number;
  /** Site public base URL — lets the scorer tell same-host internal links from external citations. */
  siteUrl?: string;
}): SeoReport {
  return scoreArticleSeo({
    title: args.title ?? '',
    slug: args.slug ?? '',
    metaDescription: args.metaDescription ?? '',
    contentMarkdown: args.contentMarkdown ?? '',
    imagePrompt: args.imagePrompt,
    primaryKeyword: args.keyword,
    bannedPhrases: args.bannedPhrases,
    inlineImageCount: args.inlineImageCount,
    internalLinkCandidates: args.internalLinkCandidates,
    siteUrl: args.siteUrl,
  });
}

/**
 * The site's existing published posts a draft may link to, with correct public
 * URLs ({baseUrl}{articlePathPrefix}/{slug}). Excludes the article being
 * (re)generated so it never links to itself. These are the ONLY valid internal
 * link targets — the model is given this list and any other internal link the
 * output contains is stripped (see stripDisallowedInternalLinks).
 */
async function listInternalLinkTargets(
  db: PrismaClient,
  site: { id: string; baseUrl: string; articlePathPrefix: string | null },
  excludeArticleId?: string,
): Promise<Array<{ title: string; url: string }>> {
  const posts = await db.article.findMany({
    where: {
      siteId: site.id,
      status: 'PUBLISHED',
      slug: { not: null },
      ...(excludeArticleId ? { id: { not: excludeArticleId } } : {}),
    },
    select: { title: true, slug: true },
    orderBy: { updatedAt: 'desc' },
    take: 50,
  });
  return posts.flatMap((post) => {
    const url = post.slug ? buildArticleUrl(site.baseUrl, site.articlePathPrefix, post.slug) : null;
    return url && post.title ? [{ title: post.title, url }] : [];
  });
}

async function createDraftRecords(
  db: PrismaClient,
  actor: Actor,
  input: ResolvedDraftTarget,
  model: string,
  draft: DraftArticle,
  seoReport: SeoReport,
  taxonomySelection: { categorySlug: string | null; tagSlugs: string[] },
  usageEntry: { usage: LlmUsage; costUsd: number },
): Promise<Article> {
  return db.$transaction(async (tx) => {
    // Automated path: consume the exact row that was claimed, so the claim is
    // always the row that gets marked DONE. Human path: upsert by term.
    const keyword = input.keywordId
      ? await tx.keyword.update({ where: { id: input.keywordId }, data: { status: 'DONE' } })
      : await tx.keyword.upsert({
          where: { siteId_term: { siteId: input.siteId, term: input.keyword } },
          create: { siteId: input.siteId, term: input.keyword, status: 'DONE' },
          update: { status: 'DONE' },
        });

    const existingArticle = await tx.article.findUnique({ where: { keywordId: keyword.id } });
    if (existingArticle) {
      throw new Error('An article already exists for this keyword.');
    }

    const contentHtml = renderBasicMarkdownToHtml(draft.contentMarkdown);
    const article = await tx.article.create({
      data: {
        siteId: input.siteId,
        keywordId: keyword.id,
        title: draft.title,
        slug: normalizeSlug(draft.slug),
        metaDescription: draft.metaDescription,
        imagePrompt: draft.imagePrompt,
        contentMarkdown: draft.contentMarkdown,
        contentHtml,
        status: 'PENDING_REVIEW',
        wordCount: wordCount(draft.contentMarkdown),
        qaReport: seoReport as Prisma.InputJsonValue,
        categorySlug: taxonomySelection.categorySlug,
        tagSlugs: taxonomySelection.tagSlugs,
        llmModel: model,
        currentVersion: 1,
        // Provenance for reporting and the review digest. Pacing deliberately
        // ignores this and counts every article, human or not.
        autoGenerated: isSystemActor(actor),
        revisions: {
          create: {
            version: 1,
            contentMarkdown: draft.contentMarkdown,
            authorType: 'AI',
            note: 'ai initial draft',
          },
        },
        images: {
          create: draft.inlineImages.map((image, index) => ({
            position: index,
            placement: image.placement,
            alt: image.alt,
            prompt: image.prompt,
            aspectRatio: image.aspectRatio,
          })),
        },
      },
      include: { keyword: true },
    });

    await recordUsage(tx, {
      articleId: article.id,
      provider: 'openrouter',
      model,
      purpose: 'draft',
      usage: usageEntry.usage,
      costUsd: usageEntry.costUsd,
    });

    await recordAudit(tx, {
      ...auditActorFields(actor),
      action: 'article.drafted',
      entityType: 'Article',
      entityId: article.id,
      metadata: {
        siteId: input.siteId,
        keyword: input.keyword,
        model,
      } as Prisma.InputJsonValue,
    });

    return article;
  });
}

