import { describe, it, expect } from 'vitest';
import { buildReviewDigest, escapeHtml, type DigestArticle } from './review-digest';

const article = (over: Partial<DigestArticle> = {}): DigestArticle => ({
  id: 'art_1',
  title: 'How to Bake Bread',
  siteName: 'Blog',
  autoGenerated: true,
  seoScore: 82,
  createdAt: new Date('2026-08-30T00:00:00Z'),
  ...over,
});

describe('escapeHtml', () => {
  it('escapes every character that could break out of the markup', () => {
    expect(escapeHtml('<script>"x"&\'y\'</script>')).toBe(
      '&lt;script&gt;&quot;x&quot;&amp;&#39;y&#39;&lt;/script&gt;',
    );
  });
});

describe('buildReviewDigest', () => {
  it('returns null below the minimum, so the cron cannot send an empty email', () => {
    expect(
      buildReviewDigest({ articles: [], appBaseUrl: 'https://app.test', minArticles: 1 }),
    ).toBeNull();
    expect(
      buildReviewDigest({ articles: [article()], appBaseUrl: 'https://app.test', minArticles: 3 }),
    ).toBeNull();
  });

  it('treats a minimum below 1 as 1, so it never sends for zero articles', () => {
    expect(
      buildReviewDigest({ articles: [], appBaseUrl: 'https://app.test', minArticles: 0 }),
    ).toBeNull();
  });

  it('builds a subject that counts correctly in both singular and plural', () => {
    const one = buildReviewDigest({
      articles: [article()],
      appBaseUrl: 'https://app.test',
      minArticles: 1,
    });
    expect(one?.subject).toBe('1 article ready for review');

    const many = buildReviewDigest({
      articles: [article(), article({ id: 'art_2' })],
      appBaseUrl: 'https://app.test',
      minArticles: 1,
    });
    expect(many?.subject).toBe('2 articles ready for review');
  });

  it('links to each article and labels its origin and score', () => {
    const digest = buildReviewDigest({
      articles: [article()],
      appBaseUrl: 'https://app.test',
      minArticles: 1,
    });
    expect(digest?.html).toContain('https://app.test/articles/art_1');
    expect(digest?.text).toContain('https://app.test/articles/art_1');
    expect(digest?.html).toContain('Blog · autopilot · SEO 82');
  });

  it('does not double up slashes when the base URL has a trailing one', () => {
    const digest = buildReviewDigest({
      articles: [article()],
      appBaseUrl: 'https://app.test/',
      minArticles: 1,
    });
    expect(digest?.text).toContain('https://app.test/articles/art_1');
    expect(digest?.text).not.toContain('//articles');
  });

  it('escapes an article title rather than trusting LLM output in HTML', () => {
    const digest = buildReviewDigest({
      articles: [article({ title: '<img src=x onerror=alert(1)>' })],
      appBaseUrl: 'https://app.test',
      minArticles: 1,
    });
    expect(digest?.html).not.toContain('<img');
    expect(digest?.html).toContain('&lt;img');
  });

  it('falls back to a placeholder for an untitled draft', () => {
    const digest = buildReviewDigest({
      articles: [article({ title: '   ' })],
      appBaseUrl: 'https://app.test',
      minArticles: 1,
    });
    expect(digest?.text).toContain('Untitled draft');
  });

  it('distinguishes manual drafts and omits a missing score', () => {
    const digest = buildReviewDigest({
      articles: [article({ autoGenerated: false, seoScore: null })],
      appBaseUrl: 'https://app.test',
      minArticles: 1,
    });
    expect(digest?.html).toContain('Blog · manual');
    expect(digest?.html).not.toContain('SEO');
  });
});
