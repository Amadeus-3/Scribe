/**
 * The review digest: what is waiting, rendered as an email.
 *
 * Pure builder only — no database, no SMTP — so it is fully unit-testable.
 * Sending lives in notify/mailer.ts.
 */

export interface DigestArticle {
  id: string;
  title: string | null;
  siteName: string;
  autoGenerated: boolean;
  seoScore: number | null;
  createdAt: Date;
}

export interface ReviewDigest {
  subject: string;
  text: string;
  html: string;
}

/** Escape text before interpolating it into the HTML body (Spec §10.1.5). */
export function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

function articleUrl(appBaseUrl: string, id: string): string {
  return `${appBaseUrl.replace(/\/+$/, '')}/articles/${id}`;
}

/**
 * Build the digest, or null when there is not enough to be worth an email.
 *
 * Returning null rather than an empty digest keeps the "don't send" decision
 * here, where it is testable, instead of in the cron.
 */
export function buildReviewDigest(input: {
  articles: DigestArticle[];
  appBaseUrl: string;
  minArticles: number;
}): ReviewDigest | null {
  const { articles, appBaseUrl, minArticles } = input;
  if (articles.length < Math.max(1, minArticles)) return null;

  const count = articles.length;
  const noun = count === 1 ? 'article' : 'articles';
  const subject = `${count} ${noun} ready for review`;

  const lines = articles.map((article) => {
    const title = article.title?.trim() || 'Untitled draft';
    const score = article.seoScore === null ? '' : ` · SEO ${article.seoScore}`;
    const origin = article.autoGenerated ? 'autopilot' : 'manual';
    return {
      title,
      meta: `${article.siteName} · ${origin}${score}`,
      url: articleUrl(appBaseUrl, article.id),
    };
  });

  const text = [
    `${count} ${noun} waiting for your review:`,
    '',
    ...lines.map((line) => `- ${line.title}\n  ${line.meta}\n  ${line.url}`),
    '',
    'Approving an article publishes it to the CMS as a draft.',
  ].join('\n');

  const html = [
    `<p>${count} ${noun} waiting for your review:</p>`,
    '<ul>',
    ...lines.map(
      (line) =>
        `<li><a href="${escapeHtml(line.url)}">${escapeHtml(line.title)}</a><br>` +
        `<small>${escapeHtml(line.meta)}</small></li>`,
    ),
    '</ul>',
    '<p>Approving an article publishes it to the CMS as a draft.</p>',
  ].join('\n');

  return { subject, text, html };
}
