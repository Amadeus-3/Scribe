-- AlterTable: provenance + digest bookkeeping.
ALTER TABLE "Article" ADD COLUMN     "autoGenerated" BOOLEAN NOT NULL DEFAULT false,
ADD COLUMN     "reviewNotifiedAt" TIMESTAMP(3);

-- AlterTable: per-site autopilot opt-in and cadence override.
ALTER TABLE "Site" ADD COLUMN     "autopilotEnabled" BOOLEAN NOT NULL DEFAULT false,
ADD COLUMN     "autopilotArticlesPerWeek" INTEGER;

